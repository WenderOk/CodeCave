def F(a, b):
    if a == b:
        return 1
    if a == 21 or a > b: # проверяем чтобы не было 21
        return 0
    if a not in F.m: # проверяем не считали ли до этого
        F.m[a] = F(a+1, b) + F(a+2, b) + F(a+3, b) # так называемая рекурентная формула. По ней вычисляем и записываем результат в кэш
    return F.m[a]
    
F.m = dict() # Создаем что-то вроде кэша чтобы не считать заново
print(F(2, 16) * F(16, 62))